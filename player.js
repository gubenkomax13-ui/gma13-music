function nextAlbumTrack(fromAlbumIndex, randomAlbum = false) {
  if (randomAlbum) return takeRandomAlbumTrack(fromAlbumIndex);
  const albumIndexes = Array.from({ length: albums.length - 1 }, (_, offset) =>
    (fromAlbumIndex + offset + 1) % albums.length);

  for (const albumIndex of albumIndexes) {
    const available = playableIndexes(albumIndex);
    if (!available.length) continue;
    const trackIndex = randomAlbum || shuffleTrackEnabled
      ? available[Math.floor(Math.random() * available.length)]
      : available[0];
    return { albumIndex, trackIndex };
  }
  return null;
}

function planNextTrack() {
  if (loadedAlbumIndex < 0 || loadedIndex < 0) return null;
  if (repeatOneEnabled) return { albumIndex: loadedAlbumIndex, trackIndex: loadedIndex };
  if (shuffleAlbumEnabled) return nextAlbumTrack(loadedAlbumIndex, true);

  const albumTracks = albums[loadedAlbumIndex].tracks;
  if (shuffleTrackEnabled && loadedAlbumIndex === currentAlbumIndex) {
    const position = shuffleOrder.indexOf(loadedIndex);
    const target = position >= 0 ? shuffleOrder[position + 1] : undefined;
    if (target !== undefined) return { albumIndex: loadedAlbumIndex, trackIndex: target };
  } else {
    for (let index = loadedIndex + 1; index < albumTracks.length; index += 1) {
      if (!isExcluded(index, loadedAlbumIndex)) return { albumIndex: loadedAlbumIndex, trackIndex: index };
    }
  }

  return nextAlbumTrack(loadedAlbumIndex);
}

function warmUpcomingTrack(target) {
  if (!target) return;
  const track = albums[target.albumIndex]?.tracks[target.trackIndex];
  if (!track) return;
  const url = new URL(track.src, location.href).href;
  if (nextTrackPreloader.src !== url) {
    nextTrackPreloader.src = url;
    nextTrackPreloader.load();
  }
  if (!prefetchedTrackUrls.has(url)) {
    prefetchedTrackUrls.add(url);
    fetch(url, { cache: "force-cache" }).catch(() => prefetchedTrackUrls.delete(url));
  }
}

function queueUpcomingTrack(force = false) {
  if (force) queuedNextTrack = null;
  if (!queuedNextTrack) queuedNextTrack = planNextTrack();
  warmUpcomingTrack(queuedNextTrack);
}

function playQueuedTrack() {
  const target = queuedNextTrack;
  if (!target) return false;
  queuedNextTrack = null;
  if (target.albumIndex === currentAlbumIndex) {
    if (shuffleTrackEnabled) shufflePosition = shuffleOrder.indexOf(target.trackIndex);
    loadTrack(target.trackIndex, true);
  } else {
    setAlbum(target.albumIndex, true, target.trackIndex);
  }
  return true;
}

function loadTrack(index, autoplay = false) {
  currentIndex = (index + tracks.length) % tracks.length;
  if (isExcluded(currentIndex)) return false;
  const track = tracks[currentIndex];

  const trackChanged = loadedAlbumIndex !== currentAlbumIndex || loadedIndex !== currentIndex;
  if (trackChanged) {
    loadedAlbumIndex = currentAlbumIndex;
    loadedIndex = currentIndex;
    if (shuffleAlbumEnabled) rememberAlbumShuffleTrack(loadedAlbumIndex, loadedIndex);
    resetListeningAnalytics();
    audio.src = track.src;
    setImageSource(playerCover, trackThumb(track, albums[loadedAlbumIndex]), albums[loadedAlbumIndex].cover);
    playerTitle.textContent = track.title;
    playerSubtitle.textContent = [albums[loadedAlbumIndex].artist, track.element].filter(Boolean).join(" · ");
    updateArtwork(track, loadedAlbumIndex);
    progress.value = 0;
    progress.style.setProperty("--value", "0%");
    currentTime.textContent = "0:00";
    duration.textContent = "0:00";
    updateMediaSession(track, loadedAlbumIndex);
  }

  updateRows();
  updateLikes();
  queueUpcomingTrack(trackChanged);
  if (autoplay) audio.play().catch(() => updateState());
  return true;
}

function updateState() {
  const playing = !audio.paused;
  const viewedAlbumIsPlaying = playing && currentAlbumIndex === loadedAlbumIndex;
  playPause.classList.toggle("is-playing", playing);
  playPause.setAttribute("aria-label", playing ? "Пауза" : "Воспроизвести");
  playPause.title = playing ? "Пауза" : "Воспроизвести";
  playAlbum.querySelector(".button-icon").textContent = icon(viewedAlbumIsPlaying);
  playAlbum.querySelector("span:last-child").textContent = viewedAlbumIsPlaying ? "Пауза" : "Слушать альбом";
  if ("mediaSession" in navigator) navigator.mediaSession.playbackState = playing ? "playing" : "paused";
  updateRows();
}

function togglePlayback() {
  if (loadedIndex < 0) {
    const index = isExcluded(currentIndex) ? playableIndexes()[0] : currentIndex;
    if (index !== undefined) loadTrack(index, true);
    else changeAlbum(1, true);
  }
  else if (audio.paused) audio.play();
  else audio.pause();
}

function toggleAlbumPlayback() {
  if (loadedAlbumIndex === currentAlbumIndex && loadedIndex >= 0) {
    if (audio.paused) audio.play();
    else audio.pause();
    return;
  }
  const index = isExcluded(currentIndex) ? playableIndexes()[0] : currentIndex;
  if (index !== undefined) loadTrack(index, true);
}

function focusLoadedAlbum() {
  if (loadedAlbumIndex < 0 || loadedIndex < 0 || !albums[loadedAlbumIndex]) return false;
  if (currentAlbumIndex !== loadedAlbumIndex) {
    currentAlbumIndex = loadedAlbumIndex;
    tracks = albums[currentAlbumIndex].tracks;
    currentIndex = loadedIndex;
    if (shuffleTrackEnabled) resetShuffle(currentIndex);
    if (shuffleAlbumEnabled) resetAlbumShuffle(currentAlbumIndex);
    updateAlbumView();
    renderTracks();
    discoverDurations();
  } else {
    currentIndex = loadedIndex;
  }
  return true;
}

function adjacentTrack(direction) {
  if (shuffleTrackEnabled) {
    const target = shufflePosition + direction;
    if (target >= 0 && target < shuffleOrder.length) {
      shufflePosition = target;
      return shuffleOrder[shufflePosition];
    }
    return null;
  }

  for (let target = currentIndex + direction; target >= 0 && target < tracks.length; target += direction) {
    if (!isExcluded(target)) return target;
  }
  return null;
}

function adjacentAlbum(direction) {
  if (albums.length < 2) return currentAlbumIndex;

  if (shuffleAlbumEnabled) {
    const target = albumShufflePosition + direction;
    if (target >= 0 && target < albumShuffleOrder.length) {
      albumShufflePosition = target;
      return albumShuffleOrder[albumShufflePosition];
    }
    resetAlbumShuffle(currentAlbumIndex);
    albumShufflePosition = direction > 0
      ? Math.min(1, albumShuffleOrder.length - 1)
      : albumShuffleOrder.length - 1;
    return albumShuffleOrder[albumShufflePosition];
  }

  return (currentAlbumIndex + direction + albums.length) % albums.length;
}

function changeAlbum(direction, autoplay = true) {
  const albumIndexes = shuffleAlbumEnabled
    ? [...shuffledAlbumIndexes(currentAlbumIndex).slice(1), currentAlbumIndex]
    : Array.from({ length: albums.length }, (_, offset) =>
      (currentAlbumIndex + direction * (offset + 1) + albums.length) % albums.length);

  for (const albumIndex of albumIndexes) {
    const available = playableIndexes(albumIndex);
    if (available.length > 0) {
      const trackIndex = direction < 0 ? available[available.length - 1] : available[0];
      if (albumIndex === currentAlbumIndex) {
        if (shuffleTrackEnabled) resetShuffle(trackIndex);
        loadTrack(trackIndex, autoplay);
      } else {
        setAlbum(albumIndex, autoplay, trackIndex);
      }
      return true;
    }
  }
  return false;
}

function changeTrack(direction) {
  focusLoadedAlbum();
  if (direction > 0 && playQueuedTrack()) return;
  const target = adjacentTrack(direction);
  if (target !== null) {
    loadTrack(target, true);
    return;
  }
  changeAlbum(direction, true);
}

function playPrevious() {
  if (audio.currentTime > 3) {
    audio.currentTime = 0;
    return;
  }
  changeTrack(-1);
}

function handleTrackEnd() {
  if (repeatOneEnabled) {
    resetListeningAnalytics();
    audio.currentTime = 0;
    audio.play();
    return;
  }
  if (playQueuedTrack()) return;
  focusLoadedAlbum();
  const target = adjacentTrack(1);
  if (target === null) {
    changeAlbum(1, true);
    return;
  }
  loadTrack(target, true);
}

function setRangeFill(input, value) {
  input.style.setProperty("--value", `${value}%`);
}

function discoverDurations() {
  const labels = document.querySelectorAll("[data-duration]");
  const durationsKnown = tracks.every((track) => Number.isFinite(track.duration));
  const total = tracks.reduce((sum, track, index) => {
    if (labels[index]) labels[index].textContent = formatTime(track.duration);
    return sum + (!isExcluded(index) && Number.isFinite(track.duration) ? track.duration : 0);
  }, 0);
  totalDuration.textContent = durationsKnown ? `${Math.round(total / 60)} мин` : "";
  durationSeparator.hidden = !durationsKnown;
}

